import express from "express";
import { join } from "node:path";
import session from "express-session";
import MongoStore from "connect-mongo";
import { errorHandler } from "./middleware/errors.js";

import type { ApolloServer } from "@apollo/server";
import { expressMiddleware } from "@as-integrations/express5";
import { createContext, type GraphQLContext } from "./graphql/context.js";
import { healthRouter } from "./routes/health.routes.js";
import { documentationRouter } from "./routes/documentation.routes.js";
import { githubRouter } from "./auth/github.routes.js";

type AppOptions = { apollo: ApolloServer<GraphQLContext> };
export function createApp({ apollo }: AppOptions) {
  const app = express();
  app.disable("x-powered-by");
  // Render terminates HTTPS at its proxy; trusting it lets secure cookies work there.
  app.set("trust proxy", process.env.NODE_ENV === "production" ? 1 : 0);
  app.use("/health", healthRouter);
  app.use("/docs", documentationRouter);
  app.get("/api-docs", (_req, res) => res.redirect(302, "/graphql"));
  app.use(express.json({ limit: "32kb" }));
  app.use((_req, res, next) => {
    res.set("Cache-Control", "no-store");
    next();
  });

  // Serve the CSS file generated by Tailwind's build step for the HTML API home page.
  app.use("/assets", express.static(join(process.cwd(), "dist/public")));

  const sessionSecret = process.env.SESSION_SECRET;
  if (!sessionSecret) {
    throw new Error("SESSION_SECRET is required to start the API.");
  }

  // Persist login state in MongoDB so it survives requests and server restarts.
  // This must run before the GitHub routes and GraphQL so both can read req.session.
  app.use(session({
    name: "app.sid",
    secret: sessionSecret,
    store: MongoStore.create({
      mongoUrl: process.env.MONGODB_URI,
    }),
    resave: false,
    saveUninitialized: false,
    cookie: {
      httpOnly: true,
      secure: process.env.NODE_ENV === "production",
      sameSite: "lax",
      maxAge: 24 * 60 * 60 * 1000,
    },
  }));

  // Mount the existing OAuth router under /auth; its callback is /auth/github/callback.
  app.use("/auth", githubRouter);

  app.get("/", (req, res) => {
    const authButtonClass =
      "inline-flex min-h-11 cursor-pointer items-center justify-center rounded-md bg-teal-300 px-4 py-2 font-semibold text-slate-950 transition-colors hover:bg-teal-200";
    const authButton = req.session.user
      ? `<form action="/auth/logout?redirect=home" method="post">
          <button class="${authButtonClass}" type="submit">Log out</button>
        </form>`
      : `<a class="${authButtonClass}" href="/auth/github">Sign in with GitHub</a>`;

    res.type("html").send(`<!doctype html>
    <html lang="en">
    <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>Students GraphQL API</title>
    <link rel="stylesheet" href="/assets/styles.css">
    </head>
    <body>
    <div class="min-h-screen bg-slate-50 font-sans text-slate-900">
      <header class="bg-slate-900 text-white">
        <nav
          aria-label="Main navigation"
          class="mx-auto flex min-h-[72px] max-w-5xl flex-wrap items-center gap-x-6 gap-y-3 px-6 py-4"
        >
          <a class="text-lg font-bold tracking-tight text-white" href="/">Students API</a>
          <div
            class="ml-auto flex flex-wrap items-center gap-5 max-sm:order-last max-sm:ml-0 max-sm:w-full"
          >
            <a
              class="text-sm font-medium text-slate-200 transition-colors hover:text-white focus-visible:rounded-sm "
              href="/docs"
            >API documentation</a>
            <a
              class="text-sm font-medium text-slate-200 transition-colors hover:text-white focus-visible:rounded-sm "
              href="/graphql"
            >GraphQL Explorer</a>
          </div>
          ${authButton}
        </nav>
      </header>
      <main class="mx-auto max-w-5xl px-6 py-16 sm:py-20">
        <h1 class="text-4xl font-bold tracking-tight text-slate-950 sm:text-5xl">
          Students GraphQL API
        </h1>
        <p class="mt-4 max-w-2xl text-lg leading-7 text-slate-600">
          Sign in with GitHub, then use the GraphQL Explorer to read and manage student records.
        </p>
      </main>
    </div>
    </body>
    </html>`);
  });
  app.use("/graphql", expressMiddleware(apollo, {
    // The context reads the session user and gives resolvers their feature services.
    context: createContext,
  }));
  app.use((_req, res) => res.status(404).json({ error: "Route not found" }));
  app.use(errorHandler);
  return app;
}
